def rows(path):
    """{a: (delta, lo, hi, improved, n, verdict)} from a routed_populations readout."""
    out = {}
    for line in open(path):
        m = re.match(r"\s+(16|32)\s+(32|64)\s*\|\s*([-+][\d.]+)\s*\[\s*([-+][\d.]+),"
                     r"\s*([-+][\d.]+)\]\s+(\d+)/(\d+)\s+(\d+)/(\d+)\s*\|\s*([A-Za-z ]+?)\s*\(", line)
        if m:
            out[int(m.group(2))] = (float(m.group(3)), float(m.group(4)), float(m.group(5)),
                                    int(m.group(6)), int(m.group(7)), m.group(10).strip())
    return out


def decoy(path):
    t = open(path).read()
    g = lambda p: re.search(p, t)
    m, d = g(r"motif\s+([-+][\d.]+) \[\s*([-+][\d.]+),\s*([-+][\d.]+)\]"), \
           g(r"rotated decoy\s+([-+][\d.]+) \[\s*([-+][\d.]+),\s*([-+][\d.]+)\]")
    f, v = g(r"retains ([-\d.]+)% of the gain"), g(r"verdict: (.+?)\s{2,}\(")
    if not (m and d and f and v):
        return None
    return (tuple(float(x) for x in m.groups()), tuple(float(x) for x in d.groups()),
            float(f.group(1)), v.group(1).strip())


def ci(vals):
    n = len(vals)
    se = st.stdev(vals) / n ** 0.5
    t = T975.get(n - 1, 1.96)
    return st.mean(vals), st.mean(vals) - t * se, st.mean(vals) + t * se


def fmt(x):
    return f"{x[0]:+.3f} [{x[1]:+.3f}, {x[2]:+.3f}]"


def tag(v):
    return "**PAYS**" if v == "PAYS" else "*unresolved*"


